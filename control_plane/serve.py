"""Packaged/dev entrypoint for the ZIMAM control plane.

Equivalent to `uvicorn zimam_control.app:app --host 127.0.0.1 --port 8876`,
but usable as a PyInstaller entry script and Windows service target.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

import uvicorn

from zimam_control.app import app

_ENV_FILE = "control-plane.env"


def _load_env_file() -> None:
    """Load KEY=VALUE pairs from control-plane.env (real env always wins).

    Scheduled tasks run as SYSTEM and cannot inherit a user profile's env vars,
    so appliance configuration (TLS paths, backup interval, ports) lives in a
    plain file next to the binaries. Checked locations, first hit wins:
    <exe dir>, <exe dir>/.. (install root for <app>/bin layout), repo root.
    """
    candidates: list[Path] = []
    if getattr(sys, "frozen", False):
        exe_dir = Path(sys.executable).resolve().parent
        candidates += [exe_dir / _ENV_FILE, exe_dir.parent / _ENV_FILE]
    repo_root = Path(__file__).resolve().parents[1]
    candidates.append(repo_root / _ENV_FILE)
    for path in candidates:
        if not path.is_file():
            continue
        for line in path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))
        return


def main() -> None:
    _load_env_file()
    # Packaged appliances need no env file: default the legacy proxy target.
    os.environ.setdefault("ZIMAM_LEGACY_API_URL", "http://127.0.0.1:8765")
    host = os.getenv("ZIMAM_HOST", "127.0.0.1")
    port = int(os.getenv("ZIMAM_CP_PORT", "8876"))
    # Optional TLS: point ZIMAM_TLS_CERT / ZIMAM_TLS_KEY at PEM files to serve
    # HTTPS directly. For LAN appliances a self-signed cert generated by
    # tools/gen-server-cert.py works; terminate at a reverse proxy otherwise.
    ssl_cert = os.getenv("ZIMAM_TLS_CERT")
    ssl_key = os.getenv("ZIMAM_TLS_KEY")
    if bool(ssl_cert) != bool(ssl_key):
        raise SystemExit("ZIMAM_TLS_CERT and ZIMAM_TLS_KEY must be set together")
    uvicorn.run(
        app,
        host=host,
        port=port,
        log_level=os.getenv("ZIMAM_LOG_LEVEL", "info"),
        ssl_certfile=ssl_cert or None,
        ssl_keyfile=ssl_key or None,
    )


if __name__ == "__main__":
    main()
