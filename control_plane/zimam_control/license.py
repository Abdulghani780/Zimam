"""ZIMAM — license model, verification, and entitlement state.

Licenses are Ed25519-signed JSON payloads delivered to customers as a single
compact string ``<base64url-json>.<base64url-signature>``. Verification is
fully local: the vendor public key is embedded below, so activation works
offline. The matching private key never ships — it lives with the vendor and
is used only by ``tools/sign-license.py``.

States
------
trial     No license installed; full enterprise features until
          ``first_boot + ZIMAM_TRIAL_DAYS`` (default 30).
licensed  Valid license; ``expires_at`` governs, ``grace_days`` of write
          access after expiry, then read-only.
expired   Past expiry + grace → mutating endpoints return 403.
"""
from __future__ import annotations

import base64
import json
import os
import time
from dataclasses import dataclass, field
from datetime import UTC, datetime

from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from cryptography.hazmat.primitives.serialization import Encoding, PublicFormat

# ---------------------------------------------------------------------------
# Vendor public key (hex, raw 32 bytes). Replace at release time with the
# production keypair; the private half is generated by tools/sign-license.py
# and must never be committed or shipped.
# ---------------------------------------------------------------------------
LICENSE_PUBLIC_KEY_HEX = os.getenv(
    "ZIMAM_LICENSE_PUBLIC_KEY",
    "",  # empty -> dev mode: licenses signed by data/license-signing.key are accepted
)

from .config import resolve_data_path

TRIAL_DAYS = int(os.getenv("ZIMAM_TRIAL_DAYS", "30"))
LICENSE_FILE = resolve_data_path(os.getenv("ZIMAM_LICENSE_FILE", "data/license.json"))
_FIRST_BOOT_FILE = resolve_data_path(os.getenv("ZIMAM_FIRST_BOOT_FILE", "data/.first_boot"))
_DEV_KEY_FILE = resolve_data_path(os.getenv("ZIMAM_LICENSE_DEV_PUBKEY_FILE", "data/license-pubkey.hex"))

VALID_TIERS = ("starter", "pro", "enterprise")

# Feature catalog. ``None`` limits mean unlimited.
TIER_DEFAULTS: dict[str, dict] = {
    "starter": {
        "max_agents": 5,
        "max_users": 1,
        "features": ["monitoring", "agents", "audit"],
    },
    "pro": {
        "max_agents": 25,
        "max_users": 5,
        "features": ["monitoring", "agents", "audit", "vault", "policies", "remote_jobs", "backup"],
    },
    "enterprise": {
        "max_agents": None,
        "max_users": None,
        "features": ["monitoring", "agents", "audit", "vault", "policies", "remote_jobs", "backup", "jit", "bastion", "sso"],
    },
}


class LicenseError(Exception):
    pass


@dataclass(frozen=True)
class License:
    license_id: str
    customer: str
    tier: str
    max_agents: int | None
    max_users: int | None
    features: frozenset[str]
    issued_at: str
    expires_at: str
    grace_days: int = 30

    @property
    def limits(self) -> dict:
        return {"max_agents": self.max_agents, "max_users": self.max_users, "features": sorted(self.features)}


def _b64url_decode(data: str) -> bytes:
    return base64.urlsafe_b64decode(data + "=" * (-len(data) % 4))


def _canonical(payload: dict) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()


def _public_key() -> Ed25519PublicKey:
    hexkey = LICENSE_PUBLIC_KEY_HEX
    if not hexkey and _DEV_KEY_FILE.exists():
        hexkey = _DEV_KEY_FILE.read_text().strip()
    if not hexkey:
        raise LicenseError("No license verification key configured")
    return Ed25519PublicKey.from_public_bytes(bytes.fromhex(hexkey))


def verify_license_token(token: str) -> License:
    """Parse and verify a compact license token. Raises LicenseError."""
    token = token.strip()
    if token.count(".") != 1:
        raise LicenseError("Malformed license token")
    payload_b64, sig_b64 = token.split(".", 1)
    try:
        raw = _b64url_decode(payload_b64)
        payload = json.loads(raw)
        signature = _b64url_decode(sig_b64)
    except Exception as exc:
        raise LicenseError("Malformed license token") from exc

    required = {"license_id", "customer", "tier", "max_agents", "max_users", "features", "issued_at", "expires_at"}
    missing = required - set(payload)
    if missing:
        raise LicenseError(f"License missing fields: {sorted(missing)}")
    if payload["tier"] not in VALID_TIERS:
        raise LicenseError(f"Unknown tier: {payload['tier']}")

    try:
        _public_key().verify(signature, _canonical(payload))
    except Exception as exc:
        raise LicenseError("License signature invalid") from exc

    # Null limits/features fall back to the tier defaults.
    defaults = TIER_DEFAULTS[payload["tier"]]
    features = payload.get("features")
    if features is None:
        features = defaults["features"]

    return License(
        license_id=str(payload["license_id"]),
        customer=str(payload["customer"]),
        tier=payload["tier"],
        max_agents=payload["max_agents"] if payload["max_agents"] is not None else defaults["max_agents"],
        max_users=payload["max_users"] if payload["max_users"] is not None else defaults["max_users"],
        features=frozenset(features),
        issued_at=str(payload["issued_at"]),
        expires_at=str(payload["expires_at"]),
        grace_days=int(payload.get("grace_days", 30)),
    )


def sign_license_payload(payload: dict, private_key_hex: str) -> str:
    """Vendor-side helper (also used by tools/sign-license.py)."""
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    from cryptography.hazmat.primitives.serialization import Encoding, NoEncryption, PrivateFormat, PublicFormat

    seed = bytes.fromhex(private_key_hex)
    key = Ed25519PrivateKey.from_private_bytes(seed)
    raw = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    sig = key.sign(raw)
    return f"{base64.urlsafe_b64encode(raw).decode().rstrip('=')}.{base64.urlsafe_b64encode(sig).decode().rstrip('=')}"


# ---------------------------------------------------------------------------
# Runtime state
# ---------------------------------------------------------------------------


def _first_boot() -> float:
    """Unix timestamp of first boot; created once and persisted."""
    if _FIRST_BOOT_FILE.exists():
        try:
            return float(_FIRST_BOOT_FILE.read_text().strip())
        except ValueError:
            pass
    now = time.time()
    _FIRST_BOOT_FILE.parent.mkdir(parents=True, exist_ok=True)
    _FIRST_BOOT_FILE.write_text(str(now))
    return now


def _parse_ts(value: str) -> float:
    return datetime.fromisoformat(value.replace("Z", "+00:00")).timestamp()


@dataclass
class LicenseState:
    mode: str  # trial | licensed | grace | expired
    license: License | None = None
    days_left: int | None = None
    trial_days_left: int | None = None
    limits: dict = field(default_factory=dict)
    features: frozenset[str] = field(default_factory=frozenset)

    def has_feature(self, feature: str) -> bool:
        return feature in self.features

    def to_dict(self) -> dict:
        lic = self.license
        return {
            "mode": self.mode,
            "tier": lic.tier if lic else ("enterprise" if self.mode == "trial" else None),
            "customer": lic.customer if lic else None,
            "license_id": lic.license_id if lic else None,
            "expires_at": lic.expires_at if lic else None,
            "days_left": self.days_left,
            "trial_days_left": self.trial_days_left,
            "limits": self.limits,
            "features": sorted(self.features),
        }


def get_license_state() -> LicenseState:
    """Resolve current license/trial state. Never raises for missing files."""
    if LICENSE_FILE.exists():
        try:
            lic = verify_license_token(LICENSE_FILE.read_bytes().decode("utf-8", errors="ignore").strip())
        except Exception:
            lic = None
        if lic is not None:
            now = time.time()
            expires = _parse_ts(lic.expires_at)
            grace_end = expires + lic.grace_days * 86400
            if now <= expires:
                mode = "licensed"
            elif now <= grace_end:
                mode = "grace"
            else:
                mode = "expired"
            days_left = max(0, int((expires - now) / 86400)) if mode != "expired" else 0
            return LicenseState(
                mode=mode,
                license=lic,
                days_left=days_left,
                limits={"max_agents": lic.max_agents, "max_users": lic.max_users, "features": sorted(lic.features)},
                features=lic.features,
            )
        # Corrupt/invalid license file falls through to trial accounting.

    trial_end = _first_boot() + TRIAL_DAYS * 86400
    now = time.time()
    trial_left = max(0, int((trial_end - now) / 86400))
    if now <= trial_end:
        feats = frozenset(TIER_DEFAULTS["enterprise"]["features"])
        return LicenseState(
            mode="trial",
            trial_days_left=trial_left,
            limits={"max_agents": None, "max_users": None, "features": sorted(feats)},
            features=feats,
        )
    return LicenseState(mode="expired", trial_days_left=0, limits={}, features=frozenset())


def activate_license(token: str) -> License:
    """Verify a token and persist it as the active license."""
    lic = verify_license_token(token)
    LICENSE_FILE.parent.mkdir(parents=True, exist_ok=True)
    LICENSE_FILE.write_bytes(token.strip().encode("utf-8"))
    try:
        LICENSE_FILE.chmod(0o600)
    except OSError:
        pass
    return lic


def deactivate_license() -> bool:
    if LICENSE_FILE.exists():
        LICENSE_FILE.unlink()
        return True
    return False
